// Writes src/conv_node_cases.rs: ToInt32 (`x | 0`) and ToUint32 (`x >>> 0`) of edge doubles,
// as node computes them. The Rust test `to_int32_matches_node` compares ep9_value against it.
//
//   node crates/ep9_value/scripts/gen-conv-cases.mjs > crates/ep9_value/src/conv_node_cases.rs
//
// The inputs are deterministic (fixed list + a seeded xorshift), so a re-run with any node
// gives the same file. No network, no dependencies.

const f64 = new Float64Array(1);
const u64 = new BigUint64Array(f64.buffer);
const bitsOf = (d) => {
  f64[0] = d;
  return u64[0];
};
const fromBits = (b) => {
  u64[0] = BigInt.asUintN(64, b);
  return f64[0];
};

const inputs = [];
const add = (d) => {
  inputs.push(d);
  inputs.push(-d);
};

// Fixed edges.
for (const d of [
  0, 0.5, 0.9999999999999999, 1, 1.5, 2, 2.5, 3.7, 255.9, 65535.5, 65536,
  2 ** 31 - 1, 2 ** 31 - 0.5, 2 ** 31, 2 ** 31 + 0.5, 2 ** 31 + 1,
  2 ** 32 - 1, 2 ** 32 - 0.5, 2 ** 32, 2 ** 32 + 0.5, 2 ** 32 + 1, 2 ** 32 * 3 + 7,
  2 ** 52, 2 ** 52 + 1, 2 ** 52 + 0.5, 2 ** 53 - 1, 2 ** 53, 2 ** 53 + 2,
  2 ** 63, 2 ** 64, 2 ** 64 + 4096, 2 ** 83, 2 ** 84, 2 ** 85,
  1e9, 1e10, 1e15, 1e16, 1e20, 1e21, 1e100, 1e300, 1.7976931348623157e308,
  2.2250738585072014e-308, 5e-324, Infinity, NaN, Math.PI * 2 ** 40,
]) {
  add(d);
}

// Powers of two near the edges of the shift rule, and their neighbours.
for (let k = 20; k <= 90; k++) {
  const p = 2 ** k;
  add(p);
  add(fromBits(bitsOf(p) + 1n)); // next double up
  add(fromBits(bitsOf(p) - 1n)); // next double down
  add(p + 2 ** 31);
  add(p - 2 ** 31);
  add(p * 1.5 + 0.25);
}

// Seeded random doubles: raw bit patterns, and magnitudes 2^0 .. 2^100.
let s = 0x0e99_5eedn;
const next = () => {
  s ^= (s << 13n) & 0xffff_ffff_ffff_ffffn;
  s ^= s >> 7n;
  s ^= (s << 17n) & 0xffff_ffff_ffff_ffffn;
  return s;
};
for (let i = 0; i < 400; i++) {
  inputs.push(fromBits(next()));
}
for (let i = 0; i < 400; i++) {
  const r = next();
  const exp = Number(r % 101n);
  const frac = Number(r >> 11n) / 2 ** 53;
  add((1 + frac) * 2 ** exp);
}

const lines = [];
const seen = new Set();
for (const d of inputs) {
  const b = bitsOf(d);
  if (seen.has(b)) continue;
  seen.add(b);
  const i32 = d | 0;
  const u32 = d >>> 0;
  lines.push(`    (0x${b.toString(16).padStart(16, "0")}, ${i32}, ${u32}),`);
}

process.stdout.write(`//! Generated by \`node crates/ep9_value/scripts/gen-conv-cases.mjs\` (node ${process.version}).
//! Do not edit. Each row: (f64 bits, \`x | 0\`, \`x >>> 0\`) as node computes them.

pub(crate) const CASES: &[(u64, i32, u32)] = &[
${lines.join("\n")}
];
`);
